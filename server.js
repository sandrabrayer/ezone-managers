// ---- upstream failure classification (shared by /api/sheets and /api/work) ----
/* Why an Apps Script call (/api/work and /api/sheets) got no usable answer → a safe code
 * the browser maps to Hebrew. Technical detail goes to the server log only:
 * the op, the class, the HTTP status, the time — never a body, a name, the
 * endpoint or the secret. */
const UPSTREAM_CODE_RE = /^[a-z][a-z_]{0,39}$/;
function workFailure(err) {
  const name = err && err.name;
  if (name === 'TimeoutError' || name === 'AbortError') return { status: 504, error: 'upstream_timeout' };
  return { status: 502, error: 'upstream_unreachable' };
}
function nonJsonFailure(text) {
  // Google answers an HTML page (not our JSON) when the script itself cannot
  // run — above all when the deploying account's authorization is missing.
  if (/authori[sz]ation is required|authorization required|permission|insufficient|consent/i.test(String(text || ''))) {
    return { status: 502, error: 'upstream_auth' };
  }
  return { status: 502, error: 'upstream_bad_response' };
}
function logWork(op, what, status, ms) {
  console.error(`[work] op=${op} ${what} status=${status} ms=${ms}`);
}

// ---- Apps Script proxy (read actions; every one needs a login) ----
const ALLOWED_QUERY_KEYS = new Set(['action', 'house', 'month']);
const ALLOWED_ACTIONS = new Set(['managersOverview', 'managersHouse', 'occupancySnapshots']);
// Backend house ids that differ from the app's keys (efroni is 'arfoni').
const BACKEND_HOUSE_IDS = { arfoni: 'efroni' };
const houseKeyOf = (id) => BACKEND_HOUSE_IDS[String(id || '')] || String(id || '');

/* A house manager's view of a feed payload: only their own house. */
function scopeForManager(action, data, house) {
  if (!data || typeof data !== 'object') return data;
  if (action === 'managersOverview') {
    const houses = Array.isArray(data.houses) ? data.houses.filter((h) => h && houseKeyOf(h.key) === house) : [];
    const own = houses[0] || {};
    return { ...data, houses, totals: { activePatients: Number(own.patientsNow) || 0 } };
  }
  if (action === 'occupancySnapshots') {
    const rows = Array.isArray(data.rows) ? data.rows.filter((r) => r && houseKeyOf(r.houseId) === house) : [];
    return { ...data, rows };
  }
  return data;
}

/* Last good read per caller (19 Oct 2026, docs/sheets-resilience.md).
 * When Apps Script fails, a read is answered from the last good copy of the
 * SAME request — same action, house, month, role and person — so a cached
 * reply can never cross a house or a person. In memory only (lost on
 * redeploy), bounded in size and age. */
const SHEETS_TIMEOUT_MS = 15000;
const SHEETS_CACHE_MAX = 100;
const SHEETS_CACHE_MAX_AGE_MS = 72 * 3600 * 1000;
const sheetsCache = new Map();
const sheetsCacheKey = (body, u) => JSON.stringify([body.action, body.house || '', body.month || '', u.role, u.id]);
function sheetsCachePut(key, text, data) {
  sheetsCache.delete(key);
  sheetsCache.set(key, { text, data, at: Date.now() });
  while (sheetsCache.size > SHEETS_CACHE_MAX) sheetsCache.delete(sheetsCache.keys().next().value);
}
function sheetsCacheGet(key) {
  const hit = sheetsCache.get(key);
  if (!hit) return null;
  if (Date.now() - hit.at > SHEETS_CACHE_MAX_AGE_MS) { sheetsCache.delete(key); return null; }
  return hit;
}
/* One safe line per failed read: action, class, status, time — never a body,
 * a name, the endpoint or the secret. */
function logSheets(action, cls, status, ms, served) {
  console.error(`[sheets] action=${action} class=${cls} status=${status} ms=${ms} served=${served}`);
}
/* A JSON reply that is not a usable feed payload (Apps Script said no). */
function sheetsReplyFailure(upstreamStatus, data) {
  if (data && data.error === 'unauthorized') return { status: 503, error: 'upstream_unavailable' };
  const bad = !data || typeof data !== 'object' || data.ok === false || data.error != null;
  if (upstreamStatus >= 200 && upstreamStatus < 300 && !bad) return null;
  return { status: 502, error: 'upstream_app_error' };
}

app.get('/api/sheets', requireUser, async (req, res) => {
  if (!allowSheets(clientIp(req))) {
    return res.status(429).json({ error: 'יותר מדי בקשות. נסו שוב מאוחר יותר.' });
  }
  const action = typeof req.query.action === 'string' ? req.query.action : '';
  if (!ALLOWED_ACTIONS.has(action)) return res.status(400).json({ error: 'unknown_action' });
  const u = req.user;
  if (action === 'managersHouse' && !access.canSeeHouse(u, String(req.query.house || ''))) {
    return res.status(403).json({ error: 'forbidden' });
  }
  const body = {};
  for (const [k, v] of Object.entries(req.query)) {
    if (ALLOWED_QUERY_KEYS.has(k) && typeof v === 'string') body[k] = v;
  }
  // Auth and scope come exclusively from the verified session, never the query.
  Object.assign(body, { secret: WORK_SECRET, role: u.role, actor: u.name, actorId: u.id });
  if (u.role !== 'admin') body.house = u.house;
  const key = sheetsCacheKey(body, u);
  res.set('Cache-Control', 'no-store');

  const send = (text, data, source, cachedAt) => {
    res.set('X-Data-Source', source);
    if (cachedAt) res.set('X-Data-Cached-At', new Date(cachedAt).toISOString());
    // A manager never receives another house's figures.
    if (u.role !== 'admin') return res.status(200).json(scopeForManager(action, data, u.house));
    return res.status(200).type('application/json').send(text);
  };
  /* A failed read: the last good copy of this exact request if there is one,
   * otherwise the safe code (the browser maps it to Hebrew). */
  const fail = (f, ms) => {
    const hit = sheetsCacheGet(key);
    logSheets(action, f.error, f.status, ms, hit ? 'cache' : 'error');
    if (hit) return send(hit.text, hit.data, 'cache', hit.at);
    return res.status(f.status).json({ error: f.error });
  };

  const started = Date.now();
  let upstream, text;
  try {
    upstream = await fetch(APPS_SCRIPT_URL, {
      method: 'POST', redirect: 'follow', signal: AbortSignal.timeout(SHEETS_TIMEOUT_MS),
      headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
      body: JSON.stringify(body)
    });
    text = await upstream.text();
  } catch (err) {
    return fail(workFailure(err), Date.now() - started);
  }
  let data;
  try { data = JSON.parse(text); } catch { return fail(nonJsonFailure(text), Date.now() - started); }
  const f = sheetsReplyFailure(upstream.status, data);
  if (f) return fail(f, Date.now() - started);
  sheetsCachePut(key, text, data);
  return send(text, data, 'live');
});

// ---- work tool: house lists + the managers' logs (Dashboard `managersWork`) ----
const WORK_OPS = new Set(['houseData', 'houseCost', 'logAdd', 'logUpdate', 'dischargeSet', 'meetingSummaries']);
// Committees are READ-ONLY here since 20 Oct 2026 (docs/committee.md): the coordinators set them in
// their app; the managers see them in houseData.committees. The old write op is GONE (410), refused
// before anything is forwarded — never reaches the Dashboard.
const RETIRED_WORK_OPS = new Set(['committeeSet']);
const WORK_LOGS = new Set(['staffTalks', 'events']);   // family calls removed from the app (14 Oct 2026)
const YM_RE = /^\d{4}-(0[1-9]|1[0-2])$/;
const ISO_DATE_RE = /^\d{4}-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01])$/;
// Writes get their own, tighter bucket on top of the shared one.
const allowWrites = makeRateLimiter({ windowMs: 15 * 60 * 1000, max: 60 });
const WRITE_OPS = new Set(['logAdd', 'logUpdate', 'dischargeSet']);
const DISCHARGE_MODES = new Set(['set', 'clear', 'none']);
// A write may wait up to 5 s for the Dashboard's script lock on top of its
// reads, so it gets a longer budget than a read (docs/expected-discharge.md).
const WORK_READ_TIMEOUT_MS = 15000;
const WORK_WRITE_TIMEOUT_MS = 30000;

app.post('/api/work', requireUser, async (req, res) => {
  res.set('Cache-Control', 'no-store');
  // JSON only: a cross-site form cannot send application/json (CSRF).
  if (!req.is('application/json')) return res.status(415).json({ error: 'json_required' });
  if (!allowSheets(clientIp(req))) {
    return res.status(429).json({ error: 'יותר מדי בקשות. נסו שוב מאוחר יותר.' });
  }
  const b = req.body || {};
  const u = req.user;
  const op = String(b.op || '');
  if (RETIRED_WORK_OPS.has(op)) {
    return res.status(410).json({ error: 'committee_read_only', message: 'את הוועדות קובעים הרכזים באפליקציית הרכזים.' });
  }
  if (!WORK_OPS.has(op)) return res.status(400).json({ error: 'unknown_op' });
  // The house is the manager's own; an admin names one.
  const house = u.role === 'admin' ? String(b.house || '') : u.house;
  if (!access.canSeeHouse(u, house) || !access.HOUSE_KEYS.includes(house)) {
    return res.status(403).json({ error: 'forbidden' });
  }
  const body = { action: 'managersWork', secret: WORK_SECRET, op, house, role: u.role, actor: u.name, actorId: u.id };
  if ((op === 'houseData' || op === 'houseCost' || op === 'meetingSummaries') && YM_RE.test(String(b.month || ''))) body.month = String(b.month);
  // «סיכומי ישיבות» (20 Oct 2026, docs/meeting-summaries.md): READ-ONLY; a bad month is refused here.
  if (op === 'meetingSummaries' && b.month != null && b.month !== '' && !YM_RE.test(String(b.month))) return res.status(400).json({ error: 'bad_month' });
  if (WRITE_OPS.has(op) && !allowWrites(clientIp(req))) {
    return res.status(429).json({ error: 'יותר מדי עדכונים. נסו שוב מאוחר יותר.' });
  }
  if (op === 'dischargeSet') {
    // Shape check only; the Dashboard re-validates (real dates, ≥ admission,
    // patient in THIS house today) and keeps the append-only audit trail.
    // mode (15 Oct 2026, docs/expected-discharge.md): 'set' (default) a date,
    // 'clear' the date, 'none' = «אין צפי לשחרור» — the last two carry no date.
    const mode = b.mode == null || b.mode === '' ? 'set' : String(b.mode);
    if (!DISCHARGE_MODES.has(mode)) return res.status(400).json({ error: 'bad_request' });
    const name = typeof b.patientName === 'string' ? b.patientName.trim() : '';
    const prev = b.previousDate == null ? '' : String(b.previousDate);
    const expected = b.expectedDate == null ? '' : String(b.expectedDate);
    if (!name || name.length > 80) return res.status(400).json({ error: 'bad_request' });
    if (!ISO_DATE_RE.test(String(b.entryDate || ''))) return res.status(400).json({ error: 'bad_date' });
    if (mode === 'set' ? !ISO_DATE_RE.test(expected) : expected !== '') return res.status(400).json({ error: 'bad_date' });
    if (prev !== '' && prev !== 'none' && !ISO_DATE_RE.test(prev)) return res.status(400).json({ error: 'bad_date' });
    if (mode === 'set' && expected < String(b.entryDate)) return res.status(400).json({ error: 'before_admission' });
    Object.assign(body, { patientName: name, entryDate: String(b.entryDate), expectedDate: expected, previousDate: prev });
    if (mode !== 'set') body.mode = mode;
  }
  if (op === 'logAdd' || op === 'logUpdate') {
    if (!WORK_LOGS.has(String(b.log || ''))) return res.status(400).json({ error: 'unknown_log' });
    body.log = String(b.log);
  }
  if (op === 'logAdd') body.entry = JSON.stringify(b.entry && typeof b.entry === 'object' ? b.entry : {});
  if (op === 'logUpdate') {
    body.id = String(b.id || '').slice(0, 64);
    const p = b.patch && typeof b.patch === 'object' ? b.patch : {};
    body.patch = JSON.stringify({ followUpDone: p.followUpDone === true, deleted: p.deleted === true });
  }
  const started = Date.now();
  try {
    const upstream = await fetch(APPS_SCRIPT_URL, {
      method: 'POST',
      redirect: 'follow',
      signal: AbortSignal.timeout(WRITE_OPS.has(op) ? WORK_WRITE_TIMEOUT_MS : WORK_READ_TIMEOUT_MS),
      headers: { 'Content-Type': 'application/json', Accept: 'application/json' },
      body: JSON.stringify(body)
    });
    const text = await upstream.text();
    let data;
    try { data = JSON.parse(text); } catch {
      const f = nonJsonFailure(text);
      logWork(op, `failure=${f.error} upstreamStatus=${upstream.status} bytes=${text.length}`, f.status, Date.now() - started);
      return res.status(f.status).json({ ok: false, error: f.error });
    }
    if (data && data.ok === false) {
      const code = typeof data.error === 'string' && UPSTREAM_CODE_RE.test(data.error) ? data.error : 'unknown';
      logWork(op, `upstreamError=${code}`, code === 'unauthorized' ? 503 : 200, Date.now() - started);
      // An Apps Script exception message is technical (server log class
      // above); the browser only gets the code.
      if (code === 'exception' || code === 'unknown') return res.status(200).json({ ok: false, error: code === 'unknown' ? 'upstream_bad_response' : 'exception' });
    }
    res.status(data && data.ok === false && data.error === 'unauthorized' ? 503 : 200).json(data);
  } catch (err) {
    const f = workFailure(err);
    logWork(op, `failure=${f.error}`, f.status, Date.now() - started);
    res.status(f.status).json({ ok: false, error: f.error });
  }
});

